fn radical_map() -> &'static HashMap<char, char> {
    static M: OnceLock<HashMap<char, char>> = OnceLock::new();
    M.get_or_init(|| {
        RADICAL_MAP
            .iter()
            .map(|&(a, b)| (char::from_u32(a).unwrap(), char::from_u32(b).unwrap()))
            .collect()
    })
}

/// 部首区码位 1:1 规整回常规 CJK（长度不变）。对齐 reverse.canon。
pub fn canon(s: &str) -> String {
    let m = radical_map();
    s.chars().map(|c| *m.get(&c).unwrap_or(&c)).collect()
}

/// 字符区间（章节全文里的字符索引，半开右端）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Range {
    pub start: usize,
    pub end: usize,
}

/// 在 haystack（字符序列）里从 from 起找 needle，返回**字符**索引。对齐 reverse.char_find。
fn char_find(haystack: &[char], needle: &[char], from: usize) -> Option<usize> {
    if needle.is_empty() {
        return Some(from);
    }
    if needle.len() > haystack.len() || from > haystack.len() - needle.len() {
        return None;
    }
    (from..=haystack.len() - needle.len()).find(|&i| &haystack[i..i + needle.len()] == needle)
}

/// 在章节原始全文里定位高亮文本 → 字符区间。段内直接 find；跨段用 head 前缀+tail 后缀锚。
/// 对齐 reverse.locate_range（去掉了 weread 特有的 page_anchor 字段，纯定位）。
/// canon 长度 1:1 不变 → 返回的字符索引对**原始** chapter_document 同样有效。
pub fn locate_range(text: &str, chapter_document: &str, from_offset: usize) -> Option<Range> {
    if text.is_empty() {
        return None;
    }
    let t: Vec<char> = canon(text).chars().collect();
    let doc: Vec<char> = canon(chapter_document).chars().collect();

    // 1) 整段连续（单段落）
    if let Some(i) = char_find(&doc, &t, from_offset) {
        return Some(Range { start: i, end: i + t.len() });
    }
    // 2) head 最长前缀（k = len-1 .. 2）
    let mut head_start: Option<usize> = None;
    let mut head_len = 0usize;
    let mut k = t.len().saturating_sub(1);
    while k > 1 {
        if let Some(j) = char_find(&doc, &t[..k], from_offset) {
            head_start = Some(j);
            head_len = k;
            break;
        }
        k -= 1;
    }
    let head_start = head_start?;
    // 3) tail 最长后缀（k = len-head_len+1 .. 2），从 head 之后找
    let mut tail_end: Option<usize> = None;
    let mut k = t.len() - head_len + 1;
    while k > 1 {
        if let Some(j) = char_find(&doc, &t[t.len() - k..], head_start + head_len) {
            tail_end = Some(j + k);
            break;
        }
        k -= 1;
    }
    let tail_end = tail_end?;
    if tail_end <= head_start {
        return None;
    }
    Some(Range { start: head_start, end: tail_end })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn canon_normalizes_radical_zone() {
        // U+2F52(部首「氏」) → U+6C0F 常规「氏」；常规字不动。
        assert_eq!(canon("\u{2f52}"), "氏");
        assert_eq!(canon("普通中文abc"), "普通中文abc");
    }

    #[test]
    fn locate_in_paragraph() {
        let doc = "骆督察一直很讨厌医院的气味。";
        let r = locate_range("讨厌", doc, 0).unwrap();
        let chars: Vec<char> = doc.chars().collect();
        assert_eq!(&chars[r.start..r.end].iter().collect::<String>(), "讨厌");
    }

    #[test]
    fn locate_radical_zone_word_hits_normal_doc() {
        // 词用部首区「氏」，文档用常规「氏」→ canon 规整后应命中。
        let doc = "他的姓氏很少见。";
        let r = locate_range("姓\u{2f52}", doc, 0).unwrap();
        let chars: Vec<char> = doc.chars().collect();
        assert_eq!(&chars[r.start..r.end].iter().collect::<String>(), "姓氏");
    }

    #[test]
    fn locate_miss_returns_none() {
        assert!(locate_range("不存在", "随便一句话", 0).is_none());
        assert!(locate_range("", "abc", 0).is_none());
    }
}
